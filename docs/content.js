const REPO = __dirname + '/../';
const FILE = (f) => fs.readFileSync(REPO + f, 'utf8').replace(/\n+$/, '').split('\n');
const sh = (cmd, input) => execSync(cmd, { input: input || '', shell: '/bin/bash' }).toString();
// translate, compile and run a PL/I source file; return output lines
const RUNSRC = (src, input, extra) => {
  const d = fs.mkdtempSync('/tmp/plrun-');
  fs.writeFileSync(d + '/s.pli', src);
  if (extra) for (const k of Object.keys(extra)) fs.writeFileSync(d + '/' + k, extra[k]);
  let out;
  try {
    out = sh('cd ' + d + ' && ' + REPO + 'pli s.pli -o s.c 2>&1 && cc -std=c89 -w -I' + REPO + 'src -o s s.c -lm 2>&1 && timeout 10 ./s 2>&1 | head -60', input);
  } catch (e) { out = 'ERROR ' + e.message; }
  sh('rm -rf ' + d);
  return out.replace(/\n+$/, '').split('\n');
};
const RUN = (f, input) => RUNSRC(fs.readFileSync(REPO + f, 'utf8'), input);
const MAIN = (body) => 'DEMO: PROCEDURE OPTIONS(MAIN);\n' + body + '\nEND DEMO;\n';
const DEMO = (fig, cap, body, input) => {
  const src = MAIN(body);
  const out = RUNSRC(src, input);
  if (out.some((l) => /^ERROR|^pli:/.test(l))) throw new Error('demo ' + fig + ': ' + out.join('\n'));
  return CODE(fig, cap, src.replace(/\n+$/, '').split('\n').concat(['', '/* prints */']).concat(out));
};
// several source files translated together into one program
const EXM = (fig, cap, files) => {
  const d = fs.mkdtempSync('/tmp/plrun-');
  files.forEach((f) => fs.copyFileSync(REPO + f, d + '/' + f.split('/').pop()));
  const names = files.map((f) => f.split('/').pop()).join(' ');
  let out;
  try {
    out = sh('cd ' + d + ' && ' + REPO + 'pli ' + names + ' -o s.c 2>&1 && cc -std=c89 -w -I' + REPO + 'src -o s s.c -lm 2>&1 && timeout 10 ./s 2>&1 | head -40');
  } catch (e) { out = 'ERROR ' + e.message; }
  sh('rm -rf ' + d);
  const lines = [];
  files.forEach((f) => { lines.push('/* ' + f.split('/').pop() + ' */'); lines.push(...FILE(f), ''); });
  return CODE(fig, cap, lines.concat(['/* pli ' + names + ' */', '/* prints */']).concat(out.replace(/\n+$/, '').split('\n')));
};
// separately compiled modules (and C files) built with -M -c
const EXMOD = (fig, cap, files, cmd) => {
  const d = fs.mkdtempSync('/tmp/plrun-');
  files.forEach((f) => fs.copyFileSync(REPO + f, d + '/' + f.split('/').pop()));
  const names = files.map((f) => f.split('/').pop()).join(' ');
  let out;
  try {
    out = sh('cd ' + d + ' && ' + REPO + 'pli ' + cmd.replace('FILES', names) + ' -o s 2>&1 && timeout 10 ./s 2>&1 | head -40');
  } catch (e) { out = 'ERROR ' + e.message; }
  sh('rm -rf ' + d);
  const lines = [];
  files.forEach((f) => { lines.push('/* ' + f.split('/').pop() + ' */'); lines.push(...FILE(f), ''); });
  return CODE(fig, cap, lines.concat(['$ pli ' + cmd.replace('FILES', names) + ' -o prog', '/* prints */']).concat(out.replace(/\n+$/, '').split('\n')));
};
const EX = (fig, cap, f, input) => CODE(fig, cap, FILE(f).concat(['', '/* prints */']).concat(RUN(f, input)));

